import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,realpathSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const require=createRequire(realpathSync(new URL('../node_modules/wrangler/package.json',import.meta.url)));
const {buildSync}=require('esbuild');
const root=fileURLToPath(new URL('..',import.meta.url));mkdirSync(root+'/work/tests',{recursive:true});
buildSync({entryPoints:[root+'/lib/plan-calendar.ts'],outfile:root+'/work/tests/plan-calendar.mjs',bundle:true,format:'esm',platform:'browser'});
const {buildPlanCalendar,venueMapUrl}=await import('../work/tests/plan-calendar.mjs');

const now=Date.parse('2026-11-01T00:00:00Z');
const event={id:'11111111-1111-4111-8111-111111111111',title:'Chai, games; hello\\again',date:'2026-11-02T18:00:00+05:30',venue:'Cafe, Ahmedabad; public table',cost:'Own order; no platform payment',description:'ગુજરાતી ચા 🍵 '.repeat(30)+'\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nATTENDEE:mailto:unwanted@example.test'};
const output=buildPlanCalendar(event,'https://momo.example/join?verify=private-token&email=private%40example.test#private',now);
const lines=output.split('\r\n');
assert.ok(lines.every(line=>Buffer.byteLength(line,'utf8')<=75),'folded lines fit 75 UTF-8 octets');
assert.ok(!output.replaceAll('\r\n','').includes('\n'),'all physical lines use CRLF');
assert.ok(!output.includes('\ufffd'),'folding must preserve Unicode code points');
const unfolded=output.replace(/\r\n /g,'');
const properties=unfolded.split('\r\n');
assert.equal(properties.filter(line=>line==='BEGIN:VEVENT').length,1,'text must not inject extra events');
assert.equal(properties.filter(line=>line.startsWith('ATTENDEE:')).length,0,'text must not inject recipients');
assert.equal(properties.filter(line=>line==='BEGIN:VALARM').length,1);assert.ok(properties.includes('ACTION:DISPLAY'));assert.ok(properties.includes('TRIGGER:-PT15M'));
assert.ok(properties.includes('DTSTART:20261102T123000Z'),'India start time is exported as the same UTC instant');
assert.ok(properties.includes('STATUS:TENTATIVE'));assert.ok(properties.includes('TRANSP:TRANSPARENT'));
assert.ok(!properties.some(line=>line.startsWith('DTEND:')||line.startsWith('DURATION:')),'no end time is invented');
assert.ok(unfolded.includes('SUMMARY:Momo plan reminder: Chai\\, games\\; hello\\\\again'));
assert.ok(unfolded.includes('ગુજરાતી ચા 🍵 '.repeat(30)),'Unicode text round trips after unfolding');
assert.ok(unfolded.includes('Full cost: Own order\\; no platform payment'));
assert.ok(unfolded.includes('place must be confirmed separately'));assert.ok(unfolded.includes('do not update automatically'));
assert.ok(properties.includes('URL:https://momo.example/join?event='+event.id));
assert.ok(!unfolded.includes('private-token'));assert.ok(!unfolded.includes('private%40'));
for(const date of ['not-a-date',new Date(now).toISOString(),new Date(now-1).toISOString()])assert.throws(()=>buildPlanCalendar({...event,date},'https://momo.example',now));
const map=new URL(venueMapUrl('Cafe & Chai #2, Ahmedabad'));
assert.equal(map.origin,'https://www.google.com');assert.equal(map.searchParams.get('query'),'Cafe & Chai #2, Ahmedabad');assert.equal(map.hash,'');assert.equal(map.searchParams.size,2);
console.log('PASS calendar time, public-only data, escaped content, Unicode folding and venue map');
