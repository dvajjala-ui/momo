// Embeds drizzle/*.sql into lib/migrations.generated.ts so non-Cloudflare
// runtimes (Vercel, local Node) can apply the same additive migrations.
import {readdirSync,readFileSync,writeFileSync} from 'node:fs';
const dir=new URL('../drizzle/',import.meta.url);
const files=readdirSync(dir).filter(f=>/^\d{4}_.+\.sql$/.test(f)).sort();
const list=files.map(f=>({name:f.replace(/\.sql$/,''),sql:readFileSync(new URL(f,dir),'utf8').replace(/\r\n/g,'\n')}));
const out=`// Generated by scripts/embed-migrations.mjs. Do not edit by hand.\nexport const migrations:{name:string;sql:string}[]=${JSON.stringify(list,null,1)};\n`;
writeFileSync(new URL('../lib/migrations.generated.ts',import.meta.url),out);
console.log('Embedded '+list.length+' migrations');
